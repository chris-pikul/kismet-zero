// Package variation provides mechanisms for modeling language variation and
// dialect formation, including automatic dialect detection, register style
// variation, and mutual intelligibility tracking. It enables realistic
// simulation of how languages diversify over time and space.
//
// Key Features:
//   - Automatic dialect detection and classification
//   - Dialect formation modeling and regional variation
//   - Register and style variation (formal, informal, technical, etc.)
//   - Mutual intelligibility calculation and tracking
//   - Geographic and social factors in variation
//   - Reproducible variation patterns through seeded RNG
//
// The package supports both natural language variation patterns and
// constructed language scenarios, providing flexible frameworks for modeling
// diverse linguistic variation contexts.
package variation
