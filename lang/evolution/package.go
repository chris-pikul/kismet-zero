// Package evolution provides mechanisms for simulating diachronic language change
// and cross-cultural linguistic influence. It enables languages to evolve over
// time through systematic sound shifts, morphological simplifications, and
// contact-induced changes like loanwords and blended phonologies.
//
// The package supports both natural evolution (internal changes over time)
// and contact evolution (influence from other languages/cultures). It maintains
// genealogical relationships between languages and tracks the history of changes
// to enable consistent world-building and historical linguistics simulation.
//
// Key Features:
//   - Sound change rules (Grimm's Law, Verner's Law analogues)
//   - Morphological evolution (simplification, regularization, innovation)
//   - Contact-induced change (borrowing, calquing, phonological adaptation)
//   - Language family tree tracking and relationship modeling
//   - Reproducible evolution through seeded RNG
//   - Cultural influence weighting and directionality
package evolution
