// Package evolution provides comprehensive mechanisms for simulating diachronic language change
// and cross-cultural linguistic influence. It enables languages to evolve over time through
// systematic sound shifts, morphological simplifications, and sophisticated contact-induced
// changes with detailed adaptation tracking.
//
// The package supports both natural evolution (internal changes over time) and contact
// evolution (influence from other languages/cultures) with enhanced linguistic adaptation
// systems. It maintains genealogical relationships between languages and tracks the history
// of changes to enable consistent world-building and historical linguistics simulation.
//
// Key Features:
//   - Advanced sound change rules with phoneme-level specifications (Grimm's Law, Verner's Law analogues)
//   - Morphological evolution (simplification, regularization, innovation)
//   - Enhanced contact-induced change with borrowing patterns and adaptation tracking
//   - Sophisticated linguistic adaptation system (phonological, grammatical, morphological)
//   - Cultural borrowing patterns with resistance and prestige sensitivity
//   - Language family tree tracking and relationship modeling
//   - Reproducible evolution through seeded RNG
//   - Cultural influence weighting and directionality
//   - Dialect formation and regional variation modeling
//   - Geographic and social dialect evolution
//   - Mutual intelligibility tracking and dialect continua
//   - Comprehensive change tracking with detailed metadata
